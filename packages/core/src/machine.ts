import type { Manifest, SiteMemory } from "@intent0/schema";
import { agentFlows } from "./mcp";

/*
 * The machine version of a site, in the llms.txt format (https://llmstxt.org): plain Markdown an
 * AI agent can read in one request instead of crawling HTML. Built from the approved manifest and
 * Site Memory, so it always matches what people see and can do.
 *   llms.txt       a map: pages, tasks agents can do, and how to connect
 *   llms-full.txt  every section of every page, with exact code blocks
 */

const oneLine = (s: string, max: number) => {
  const t = s.replace(/\s+/g, " ").trim();
  return t.length > max ? `${t.slice(0, max - 1).trimEnd()}…` : t;
};

/** `mcpUrl`: where intent0 itself runs, if not on the site (e.g. `intent0 serve` on another port). */
export function llmsTxt(manifest: Manifest, memory: SiteMemory | null, base: string, mcpUrl = new URL("/intent0/mcp", base).toString()): string {
  const abs = (url: string) => new URL(url, base).toString();
  const out: string[] = [`# ${manifest.site.name}`, ""];
  out.push(`> ${manifest.site.name}, prepared for AI agents by intent0: what the site says, and what an agent can do on it.`, "");

  if (memory?.pages.length) {
    out.push("## Pages", "");
    for (const p of memory.pages) {
      const first = memory.sections.find((s) => s.page === p.id && s.text);
      out.push(`- [${p.title}](${abs(p.url)})${first ? `: ${oneLine(first.text, 140)}` : ""}`);
    }
    out.push("");
  }

  const flows = agentFlows(manifest);
  if (flows.length) {
    out.push("## Tasks an agent can do", "");
    for (const f of flows) {
      const fields = f.steps.flatMap((s) => s.fields).filter((x) => x.type !== "otp");
      const details = fields.map((x) => `${x.name}${x.required ? "" : " (optional)"}${x.options ? ` [${x.options.map((o) => o.value).join(", ")}]` : ""}`).join(", ");
      out.push(`- ${f.id}: ${f.title}. ${oneLine(f.description, 160)}${details ? ` Details: ${details}.` : ""}${f.irreversible ? " Can't be undone: confirm with the person first." : ""}`);
    }
    out.push("");
  }

  out.push("## For AI agents", "");
  out.push(`- MCP server (Streamable HTTP): ${mcpUrl}. Tools: ${[...flows.map((f) => f.id), ...(memory?.sections.length ? ["search_site"] : [])].join(", ") || "none"}.`);
  if (memory?.sections.length) out.push(`- Full content as text: ${abs("/llms-full.txt")}`);
  out.push("- Rules: only the tasks above are available; required steps such as OTP can't be skipped; irreversible tasks need confirmed: true, sent only after the person agrees.");
  out.push("");
  return out.join("\n");
}

export function llmsFullTxt(manifest: Manifest, memory: SiteMemory | null, base: string): string {
  const out: string[] = [`# ${manifest.site.name}`, "", `> Every page of ${manifest.site.name} as plain text, for AI agents. Generated by intent0 from Site Memory.`, ""];
  for (const p of memory?.pages ?? []) {
    out.push(`## ${p.title}`, "", `Source: ${new URL(p.url, base).toString()}`, "");
    for (const s of memory!.sections.filter((x) => x.page === p.id)) {
      const heading = s.path.at(-1);
      if (heading && heading !== p.title) out.push(`### ${heading}`, "");
      if (s.text) out.push(s.text, "");
      for (const c of s.code) out.push(`\`\`\`${c.lang}`, c.code, "```", "");
    }
  }
  return out.join("\n");
}
